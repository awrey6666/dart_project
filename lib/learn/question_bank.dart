import 'content_store.dart';
import 'learn_catalog.dart';
import 'learn_models.dart';

/// Նախապես պատրաստված հարցեր (բոլոր առարկաներ, տարբեր տիպեր և բարդություններ)։
///
/// [all]-ը միշտ ներկառուցված հարցերն են։ [forTopic]-ը վերադարձնում է ընթացիկ
/// հարցերը՝ հաշվի առնելով ադմինի փոփոխությունները ([ContentStore])։
class QuestionBank {
  QuestionBank._();

  static List<Question>? _cache;

  static List<Question> get all => _cache ??= _build();

  static List<Question> forTopic(String topicId) =>
      ContentStore.instance.questionsFor(topicId);

  static List<Question> _build() {
    final out = <Question>[];
    final counters = <String, int>{};

    String idFor(String topic) {
      final n = (counters[topic] ?? 0) + 1;
      counters[topic] = n;
      return '$topic.$n';
    }

    String subjectOf(String topic) => builtinTopicById(topic)!.subjectId;

    void mc(String t, int d, String prompt, List<String> options, int answer, String why) {
      out.add(Question(
        id: idFor(t),
        subjectId: subjectOf(t),
        topicId: t,
        type: QuestionType.multipleChoice,
        difficulty: d,
        prompt: prompt,
        options: options,
        answerIndex: answer,
        explanation: why,
      ));
    }

    void tf(String t, int d, String prompt, bool answer, String why) {
      out.add(Question(
        id: idFor(t),
        subjectId: subjectOf(t),
        topicId: t,
        type: QuestionType.trueFalse,
        difficulty: d,
        prompt: prompt,
        options: const ['Ճիշտ', 'Սխալ'],
        answerIndex: answer ? 0 : 1,
        explanation: why,
      ));
    }

    void fill(String t, int d, String prompt, List<String> accepted, String why) {
      out.add(Question(
        id: idFor(t),
        subjectId: subjectOf(t),
        topicId: t,
        type: QuestionType.fillBlank,
        difficulty: d,
        prompt: prompt,
        accepted: accepted,
        explanation: why,
      ));
    }

    void code(String t, int d, String prompt, List<String> accepted, String why) {
      out.add(Question(
        id: idFor(t),
        subjectId: subjectOf(t),
        topicId: t,
        type: QuestionType.code,
        difficulty: d,
        prompt: prompt,
        accepted: accepted,
        explanation: why,
      ));
    }

    void numq(String t, int d, String prompt, double answer, String why) {
      out.add(Question(
        id: idFor(t),
        subjectId: subjectOf(t),
        topicId: t,
        type: QuestionType.numeric,
        difficulty: d,
        prompt: prompt,
        numericAnswer: answer,
        explanation: why,
      ));
    }

    void order(String t, int d, String prompt, List<String> correct, String why) {
      out.add(Question(
        id: idFor(t),
        subjectId: subjectOf(t),
        topicId: t,
        type: QuestionType.ordering,
        difficulty: d,
        prompt: prompt,
        options: correct,
        explanation: why,
      ));
    }

    void match(String t, int d, String prompt, List<List<String>> pairs, String why) {
      out.add(Question(
        id: idFor(t),
        subjectId: subjectOf(t),
        topicId: t,
        type: QuestionType.matching,
        difficulty: d,
        prompt: prompt,
        options: [for (final p in pairs) p[0]],
        rights: [for (final p in pairs) p[1]],
        explanation: why,
      ));
    }

    void open(String t, int d, String prompt, List<String> keywords, String why) {
      out.add(Question(
        id: idFor(t),
        subjectId: subjectOf(t),
        topicId: t,
        type: QuestionType.open,
        difficulty: d,
        prompt: prompt,
        keywords: keywords,
        explanation: why,
      ));
    }

    // ========================= DART =========================
    const dv = 'dart.vars';
    mc(dv, 1, 'Ո՞ր բառով հայտարարված փոփոխականին արժեք կարելի է վերագրել միայն մեկ անգամ։',
        ['var', 'final', 'dynamic', 'int'], 1,
        'final փոփոխականը ստանում է արժեք մեկ անգամ և հետո չի փոխվում։');
    tf(dv, 1, 'Dart-ում `int x = 3.5;` գրառումը սխալ է։', true,
        '3.5-ը double է, իսկ int-ին կարելի է վերագրել միայն ամբողջ թիվ։');
    code(dv, 2, 'Ի՞նչ կտպի կոդը՝\nvar a = 7;\nvar b = 2;\nprint(a ~/ b);', ['3'],
        '~/ օպերատորը ամբողջ թվերի բաժանումն է՝ 7 ~/ 2 = 3։');
    fill(dv, 2, 'String? name; փոփոխականը կարող է պարունակել null, որովհետև տիպից հետո դրված է ___ նշանը։',
        ['?'], '? նշանը տիպը դարձնում է nullable։');
    mc(dv, 3, 'Ի՞նչ կլինի՝\nconst list = [1, 2];\nlist.add(3);',
        ['3-ը կավելանա', 'Աշխատանքի ժամանակ կլինի սխալ (Unsupported operation)', 'Կվերադարձվի null', 'Ոչինչ չի լինի'],
        1, 'const ցուցակը անփոփոխ է, add-ը կառաջացնի սխալ։');

    const dc = 'dart.cond';
    tf(dc, 1, 'Dart-ում if-ի պայմանը պետք է լինի bool տիպի (0-ն և null-ը ինքնին false չեն)։', true,
        'Dart-ը խիստ է. պայմանը պետք է լինի true կամ false։');
    mc(dc, 2, 'Ո՞րն է ternary օպերատորի ճիշտ գրելաձևը։',
        ['x > 0 ? "դրական" : "ոչ դրական"', 'if x > 0 then "դրական" else "ոչ դրական"', 'x > 0 : "դրական" ? "ոչ դրական"', 'x > 0 ?? "դրական" : "ոչ դրական"'],
        0, 'Ձևը՝ պայման ? արժեքԵթեTrue : արժեքԵթեFalse։');
    code(dc, 3, 'Ի՞նչ կտպի՝\nint n = 5;\nprint(n > 3 && n < 5);', ['false'],
        'n > 3 true է, իսկ n < 5՝ false։ true && false = false։');
    code(dc, 4, "Ի՞նչ կտպի՝\nString? s;\nprint(s ?? 'նոր');", ['նոր'],
        '?? օպերատորը վերցնում է աջ արժեքը, եթե ձախը null է։');
    fill(dc, 2, 'Եթե երկու պայմաններից առնվազն մեկը true է, օգտագործվում է ___ օպերատորը (գրեք նշանով)։',
        ['||'], '|| նշանակում է «կամ»։');

    const dl = 'dart.loops';
    numq(dl, 1, 'Քանի՞ անգամ կկատարվի ցիկլի մարմինը՝\nfor (var i = 0; i < 4; i++) { }', 4,
        'i-ն ընդունում է 0, 1, 2, 3 արժեքները՝ 4 կրկնություն։');
    order(dl, 2, 'Դասավորեք for ցիկլի քայլերը կատարման հերթականությամբ։', [
      'Սկզբնական արժեքի վերագրում (i = 0)',
      'Պայմանի ստուգում (i < n)',
      'Մարմնի կատարում',
      'Հաշվիչի փոփոխություն (i++)',
    ], 'Սկզբում սկզբնավորում, հետո պայման, մարմին, քայլ, հետո նորից պայման։');
    code(dl, 3, 'Ի՞նչ կտպի՝\nvar sum = 0;\nfor (var i = 1; i <= 4; i++) {\n  sum += i;\n}\nprint(sum);', ['10'],
        '1 + 2 + 3 + 4 = 10։');
    mc(dl, 3, 'Ո՞ր հրամանն է անմիջապես դադարեցնում ցիկլը։', ['continue', 'break', 'skip', 'pass'], 1,
        'break-ը դուրս է գալիս ցիկլից, continue-ն անցնում է հաջորդ քայլին։');
    code(dl, 4,
        'Ի՞նչ կտպվի (առանց բացատրի)՝\nfor (var i = 0; i < 5; i++) {\n  if (i == 2) continue;\n  if (i == 4) break;\n  stdout.write(i);\n}',
        ['013', '0 1 3'], 'i=2-ը բաց է թողնվում, i=4-ի դեպքում ցիկլը դադարում է՝ տպվում է 0, 1, 3։');

    const df = 'dart.funcs';
    fill(df, 1, 'Եթե ֆունկցիան արժեք չի վերադարձնում, վերադարձի տիպը գրվում է ___։', ['void'],
        'void նշանակում է «ոչինչ չի վերադարձվում»։');
    code(df, 2, 'Ի՞նչ կտպի՝\nint add(int a, int b) => a + b;\nprint(add(2, 3));', ['5'],
        '=> ձևը կարճ return է։');
    mc(df, 3, 'Ինչպե՞ս են Dart-ում հայտարարվում անվանված (named) պարամետրերը։',
        ['f(int a, int b)', 'f({int? a, int? b})', 'f(named int a)', 'f(<int a>)'], 1,
        'Անվանված պարամետրերը գրվում են գանգուր փակագծերում։');
    match(df, 3, 'Համապատասխանեցրեք Dart-ի տիպերը։', [
      ['int', 'Ամբողջ թիվ'],
      ['double', 'Տասնորդական թիվ'],
      ['String', 'Տեքստ'],
      ['bool', 'true / false'],
    ], 'Հիմնական տիպերի նշանակությունը։');
    open(df, 4, 'Բացատրեք՝ ի՞նչ տարբերություն կա final-ի և const-ի միջև։',
        ['կոմպիլ', 'մեկ անգամ', 'final', 'const'],
        'final-ը արժեք է ստանում մեկ անգամ աշխատանքի ժամանակ, const-ը՝ արդեն կոմպիլյացիայի ժամանակ։');

    // ========================= JAVA =========================
    const jb = 'java.basics';
    mc(jb, 1, 'Ո՞րն է Java-ում ամբողջ թվի պրիմիտիվ տիպը։', ['int', 'Integer', 'Number', 'integer'], 0,
        'int-ը պրիմիտիվ է, Integer-ը՝ դրա wrapper դասը։');
    code(jb, 2, 'Ի՞նչ կտպի՝\nint a = 7 / 2;\nSystem.out.println(a);', ['3'],
        'Ամբողջ թվերի բաժանումը կտրում է կոտորակային մասը։');
    tf(jb, 2, 'Java-ում String-ները պետք է համեմատել equals() մեթոդով, ոչ թե == օպերատորով։', true,
        '== համեմատում է հղումները, equals()-ը՝ պարունակությունը։');
    code(jb, 3, 'Ի՞նչ կտպի՝\nSystem.out.println(10 % 4);', ['2'], '10 = 2·4 + 2, մնացորդը 2 է։');
    mc(jb, 4, 'Ի՞նչ կտպի System.out.println("5" + 3 + 2);', ['10', '532', '55', 'Սխալ'], 1,
        'Տողին թիվ ավելացնելիս կատարվում է կոնկատենացիա՝ "5"+"3"+"2" = "532"։');

    const jo = 'java.oop';
    fill(jo, 1, 'Օբյեկտ ստեղծելու համար Java-ում օգտագործվում է ___ բառը։', ['new'], 'new Car() ստեղծում է օբյեկտ։');
    mc(jo, 2, 'Ո՞ր բառով է դասը ժառանգում մեկ այլ դասից։', ['implements', 'extends', 'inherits', 'super'], 1,
        'class B extends A։ implements-ը interface-ի համար է։');
    match(jo, 2, 'Համապատասխանեցրեք մոդիֆիկատորները։', [
      ['private', 'Հասանելի է միայն նույն դասում'],
