class AdminTopicPage extends StatelessWidget {
  const AdminTopicPage({super.key, required this.topicId});

  final String topicId;

  Future<void> _delete(BuildContext context, Topic topic, Question question) async {
    final learn = LearnScope.of(context);
    final ok = await confirmDelete(
      context,
      title: 'Ջնջե՞լ հարցը',
      message: question.prompt,
    );
    if (!ok) return;
    final error = await learn.deleteQuestion(topic.id, question.id);
    if (context.mounted) showStudyMessage(context, error);
  }

  @override
  Widget build(BuildContext context) {
    final learn = LearnScope.of(context);
    if (!learn.isAdmin) return const _NoAccess();
    final topic = topicById(topicId);
    if (topic == null) return const _NotFound(what: 'Թեման');
    final scheme = Theme.of(context).colorScheme;
    // Դասավորում ենք ըստ բարդության. նույն բարդության հարցերի հերթականությունը պահպանվում է։
    final all = ContentStore.instance.questionsFor(topic.id);
    final position = {for (var i = 0; i < all.length; i++) all[i].id: i};
    final questions = [...all]
      ..sort((a, b) {
        final byDifficulty = a.difficulty.compareTo(b.difficulty);
        return byDifficulty != 0
            ? byDifficulty
            : position[a.id]!.compareTo(position[b.id]!);
      });

    return Scaffold(
      appBar: AppBar(title: Text(topic.title)),
      floatingActionButton: FloatingActionButton.extended(
        onPressed: () => _open(context, QuestionEditorPage(topic: topic)),
        icon: const Icon(Icons.add),
        label: const Text('Նոր հարց'),
      ),
      body: Center(
        child: ConstrainedBox(
          constraints: const BoxConstraints(maxWidth: 860),
          child: ListView(
            padding: const EdgeInsets.fromLTRB(16, 8, 16, 96),
            children: [
              Card(
                child: Padding(
                  padding: const EdgeInsets.all(12),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Row(
                        children: [
                          const Expanded(
                            child: Text(
                              'Բացատրություն',
                              style: TextStyle(fontWeight: FontWeight.w700),
                            ),
                          ),
                          TextButton.icon(
                            onPressed: () => showDialog<bool>(
                              context: context,
                              builder: (_) => _TopicDialog(
                                subjectId: topic.subjectId,
                                existing: topic,
                              ),
                            ),
                            icon: const Icon(Icons.edit_outlined),
                            label: const Text('Խմբագրել'),
                          ),
                        ],
                      ),
                      Text(
                        topic.tip.isEmpty ? 'Բացատրություն դեռ չկա։' : topic.tip,
                        style: TextStyle(color: scheme.onSurfaceVariant),
                      ),
                    ],
                  ),
                ),
              ),
              if (_autoGeneratedTopics.contains(topic.id)) ...[
                const SizedBox(height: 8),
                Card(
                  color: scheme.secondaryContainer,
                  child: Padding(
                    padding: const EdgeInsets.all(12),
                    child: Text(
                      'Այս թեմայում դասերի ժամանակ լրացուցիչ ավտոմատ գեներացվող '
                      'թվային հարցեր էլ են հայտնվում։ Դրանք այստեղ չեն երևում և չեն խմբագրվում։',
                      style: TextStyle(color: scheme.onSecondaryContainer),
                    ),
                  ),
                ),
              ],
              const SizedBox(height: 12),
              SectionHeader(title: 'Հարցեր (${questions.length})'),
              if (questions.isEmpty)
                const EmptyHint(
                  icon: Icons.quiz_outlined,
                  message: 'Այս թեման դեռ հարցեր չունի։ Ավելացրեք առաջինը։',
                ),
              for (final q in questions)
                Card(
                  child: ListTile(
                    leading: Tooltip(
                      message: 'Բարդություն ${q.difficulty}/5',
                      child: CircleAvatar(child: Text('${q.difficulty}')),
                    ),
                    title: Text(q.prompt, maxLines: 2, overflow: TextOverflow.ellipsis),
                    subtitle: Text(
                      '${q.type.label} · ${_shorten(q.correctAnswerText)}',
                      maxLines: 1,
                      overflow: TextOverflow.ellipsis,
                    ),
                    onTap: () => _open(context, QuestionEditorPage(topic: topic, existing: q)),
                    trailing: IconButton(
                      tooltip: 'Ջնջել',
                      icon: const Icon(Icons.delete_outline),
                      onPressed: () => _delete(context, topic, q),
                    ),
                  ),
                ),
            ],
          ),
        ),
      ),
    );
  }

  static String _shorten(String text) {
    final flat = text.replaceAll('\n', ' · ');
    return flat.length <= 60 ? flat : '${flat.substring(0, 60)}…';
  }
}

