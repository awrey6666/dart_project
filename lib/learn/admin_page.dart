// Նոր հաշվի ստեղծում ադմինի կողմից
// ---------------------------------------------------------------------------

class _AccountDialog extends StatefulWidget {
  const _AccountDialog();

  @override
  State<_AccountDialog> createState() => _AccountDialogState();
}

class _AccountDialogState extends State<_AccountDialog> {
  final _name = TextEditingController();
  final _password = TextEditingController();
  var _hidden = true;
  var _busy = false;
  String? _error;

  @override
  void dispose() {
    _name.dispose();
    _password.dispose();
    super.dispose();
  }

  Future<void> _save() async {
    final learn = LearnScope.of(context);
    setState(() {
      _busy = true;
      _error = null;
    });
    final error = await learn.addAccount(_name.text, _password.text);
    if (!mounted) return;
    if (error != null) {
      setState(() {
        _busy = false;
        _error = error;
      });
      return;
    }
    Navigator.of(context).pop(true);
  }

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    return AlertDialog(
      title: const Text('Նոր հաշիվ'),
      content: SizedBox(
        width: 420,
        child: SingleChildScrollView(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              TextField(
                controller: _name,
                autofocus: true,
                decoration: const InputDecoration(labelText: 'Անուն'),
              ),
              const SizedBox(height: 12),
              TextField(
                controller: _password,
                obscureText: _hidden,
                decoration: InputDecoration(
                  labelText: 'Գաղտնաբառ (առնվազն 4 նիշ)',
                  suffixIcon: IconButton(
                    tooltip: _hidden ? 'Ցույց տալ' : 'Թաքցնել',
                    icon: Icon(
                      _hidden ? Icons.visibility_outlined : Icons.visibility_off_outlined,
                    ),
                    onPressed: () => setState(() => _hidden = !_hidden),
                  ),
                ),
              ),
              if (_error != null)
                Align(
                  alignment: Alignment.centerLeft,
                  child: Text(_error!, style: TextStyle(color: scheme.error)),
                ),
            ],
          ),
        ),
      ),
      actions: [
        TextButton(
          onPressed: _busy ? null : () => Navigator.of(context).pop(false),
          child: const Text('Չեղարկել'),
        ),
        FilledButton(
          onPressed: _busy ? null : _save,
          child: const Text('Ստեղծել'),
        ),
      ],
    );
  }
}
