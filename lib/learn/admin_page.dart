class AdminUsersPage extends StatelessWidget {
  const AdminUsersPage({super.key});

  @override
  Widget build(BuildContext context) {
    final learn = LearnScope.of(context);
    if (!learn.isAdmin) return const _NoAccess();
    final accounts = learn.accounts;
    return Scaffold(
      appBar: AppBar(title: const Text('Օգտատերեր')),
      floatingActionButton: FloatingActionButton.extended(
        onPressed: () => showDialog<bool>(
          context: context,
          builder: (_) => const _AccountDialog(),
        ),
        icon: const Icon(Icons.person_add_alt_1_outlined),
        label: const Text('Նոր հաշիվ'),
      ),
      body: Center(
        child: ConstrainedBox(
          constraints: const BoxConstraints(maxWidth: 720),
          child: ListView(
            padding: const EdgeInsets.fromLTRB(16, 8, 16, 96),
            children: [
              const Padding(
                padding: EdgeInsets.only(bottom: 8),
                child: Text(
                  'Ադմինի վահանակը հասանելի է միայն ադմինի մուտքանունով և գաղտնաբառով։ '
                  'Այստեղ կարող եք ստեղծել սովորողների հաշիվներ։',
                ),
              ),
              Card(
                child: SwitchListTile(
                  secondary: const Icon(Icons.shield_outlined),
                  title: const Text('Սովորողների մուտքը փակ է'),
                  subtitle: Text(
                    learn.adminOnlyLogin
                        ? 'Սովորողները չեն կարող մուտք գործել, և ինքնուրույն գրանցումը փակ է։ '
                              'Հաշիվները ստեղծում եք դուք՝ «Նոր հաշիվ» կոճակով։'
                        : 'Մուտք գործել և գրանցվել կարող են բոլորը։',
                  ),
                  value: learn.adminOnlyLogin,
                  onChanged: (value) async =>
                      showStudyMessage(context, await learn.setAdminOnlyLogin(value)),
                ),
              ),
              const SizedBox(height: 8),
              if (accounts.isEmpty)
                const EmptyHint(
                  icon: Icons.group_outlined,
                  message: 'Սովորողների հաշիվներ դեռ չկան։',
                ),
              for (final account in accounts)
                Card(
                  child: ListTile(
                    leading: CircleAvatar(
                      child: Text(account.name.characters.first.toUpperCase()),
                    ),
                    title: Text(account.name),
                    subtitle: const Text('Սովորող'),
                  ),
                ),
            ],
          ),
        ),
      ),
    );
  }
}

