    final learn = LearnScope.of(context);
    final ok = await confirmDelete(
      context,
      title: 'Ջնջե՞լ «${subject.title}» առարկան',
      message:
          'Կջնջվեն առարկայի ${subject.topics.length} թեմաները և բոլոր հարցերը։ '
