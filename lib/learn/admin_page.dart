class _SubjectDialog extends StatefulWidget {
  const _SubjectDialog({this.existing});

  final LearnSubject? existing;

  @override
  State<_SubjectDialog> createState() => _SubjectDialogState();
}

class _SubjectDialogState extends State<_SubjectDialog> {
  late final TextEditingController _title;
  late final TextEditingController _group;
  late int _color;
  var _busy = false;
  String? _error;

  @override
  void initState() {
    super.initState();
    final existing = widget.existing;
    _title = TextEditingController(text: existing?.title ?? '');
    final groups = learnGroups;
    _group = TextEditingController(
      text: existing?.group ?? (groups.isEmpty ? defaultGroups.first : groups.first),
    );
    _color = existing?.colorValue ?? _palette.first;
  }

  @override
  void dispose() {
    _title.dispose();
    _group.dispose();
    super.dispose();
  }

  Future<void> _save() async {
    final learn = LearnScope.of(context);
    setState(() {
      _busy = true;
      _error = null;
    });
    final error = await learn.saveSubject(
      id: widget.existing?.id,
      title: _title.text,
      group: _group.text,
      colorValue: _color,
    );
    if (!mounted) return;
    if (error != null) {
      setState(() {
        _busy = false;
        _error = error;
      });
      return;
    }
    Navigator.of(context).pop(true);
  }

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    final groups = <String>{...defaultGroups, ...learnGroups};
    return AlertDialog(
      title: Text(widget.existing == null ? 'Նոր առարկա' : 'Խմբագրել առարկան'),
      content: SizedBox(
        width: 440,
        child: SingleChildScrollView(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              TextField(
                controller: _title,
                autofocus: true,
                textCapitalization: TextCapitalization.sentences,
                decoration: const InputDecoration(labelText: 'Առարկայի անուն'),
              ),
              const SizedBox(height: 12),
              TextField(
                controller: _group,
                decoration: const InputDecoration(
                  labelText: 'Խումբ',
                  helperText: 'Ընտրեք ներքևից կամ գրեք նոր խմբի անուն',
                ),
              ),
              const SizedBox(height: 8),
              Wrap(
                spacing: 6,
                runSpacing: 4,
                children: [
                  for (final group in groups)
                    ActionChip(
                      label: Text(group),
                      onPressed: () => setState(() => _group.text = group),
                    ),
                ],
              ),
              const SizedBox(height: 16),
              const Text('Գույն'),
              const SizedBox(height: 8),
              Wrap(
                spacing: 8,
                runSpacing: 8,
                children: [
                  for (final value in _palette)
                    InkWell(
                      customBorder: const CircleBorder(),
                      onTap: () => setState(() => _color = value),
                      child: CircleAvatar(
                        radius: 16,
                        backgroundColor: Color(value),
                        child: _color == value
                            ? const Icon(Icons.check, size: 18, color: Colors.white)
                            : null,
                      ),
                    ),
                ],
              ),
              if (_error != null) ...[
                const SizedBox(height: 12),
                Text(_error!, style: TextStyle(color: scheme.error)),
              ],
            ],
          ),
        ),
      ),
      actions: [
        TextButton(
          onPressed: _busy ? null : () => Navigator.of(context).pop(false),
          child: const Text('Չեղարկել'),
        ),
        FilledButton(
          onPressed: _busy ? null : _save,
          child: const Text('Պահել'),
        ),
      ],
    );
  }
}

