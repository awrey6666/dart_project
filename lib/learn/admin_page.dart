class QuestionEditorPage extends StatefulWidget {
  const QuestionEditorPage({super.key, required this.topic, this.existing});

  final Topic topic;
  final Question? existing;

  @override
  State<QuestionEditorPage> createState() => _QuestionEditorPageState();
}

class _QuestionEditorPageState extends State<QuestionEditorPage> {
  static const _maxChoices = 6;
  static const _maxItems = 8;
  static const _maxPairs = 6;

  late QuestionType _type;
  late int _difficulty;
  late final TextEditingController _prompt;
  late final TextEditingController _explanation;
  late final TextEditingController _accepted;
  late final TextEditingController _numeric;
  late final TextEditingController _keywords;

  /// multipleChoice՝ տարբերակներ, ordering՝ տարրեր, matching՝ ձախ մասեր։
  final _options = <TextEditingController>[];

  /// matching՝ աջ մասեր։
  final _rights = <TextEditingController>[];

  /// multipleChoice՝ ճիշտ տարբերակի ինդեքսը, trueFalse՝ 0 = ճիշտ, 1 = սխալ։
  var _answerIndex = 0;

  // Հեռացված դաշտերի controller-ները վերացվում են միայն էջը փակելիս,
  // որպեսզի TextField-ը չօգտագործի արդեն dispose արված controller։
  final _retired = <TextEditingController>[];

  var _busy = false;
  String? _error;

  @override
  void initState() {
    super.initState();
    final q = widget.existing;
    _type = q?.type ?? QuestionType.multipleChoice;
    _difficulty = q?.difficulty ?? 2;
    _prompt = TextEditingController(text: q?.prompt ?? '');
    _explanation = TextEditingController(text: q?.explanation ?? '');
    _accepted = TextEditingController(text: q?.accepted.join('\n') ?? '');
    _keywords = TextEditingController(text: q?.keywords.join(', ') ?? '');
    final numeric = q?.numericAnswer;
    _numeric = TextEditingController(
      text: numeric == null
          ? ''
          : (numeric == numeric.roundToDouble() ? '${numeric.toInt()}' : '$numeric'),
    );
    if (q != null) {
      for (final text in q.options) {
        _options.add(TextEditingController(text: text));
      }
      for (final text in q.rights) {
        _rights.add(TextEditingController(text: text));
      }
      _answerIndex = q.answerIndex;
    }
    _ensureRows();
  }

  @override
  void dispose() {
    for (final c in [
      _prompt,
      _explanation,
      _accepted,
      _numeric,
      _keywords,
      ..._options,
      ..._rights,
      ..._retired,
    ]) {
      c.dispose();
    }
    super.dispose();
  }

  int get _minRows => switch (_type) {
    QuestionType.multipleChoice => 4,
    QuestionType.ordering => 3,
    QuestionType.matching => 3,
    _ => 0,
  };

  /// Ապահովում է, որ ընթացիկ տեսակի համար բավարար դատարկ դաշտեր կան։
  void _ensureRows() {
    final need = _minRows;
    while (_options.length < need) {
      _options.add(TextEditingController());
    }
    if (_type == QuestionType.matching) {
      while (_rights.length < _options.length) {
        _rights.add(TextEditingController());
      }
    }
  }

  void _changeType(QuestionType type) {
    setState(() {
      _type = type;
      _answerIndex = 0;
      _error = null;
      _ensureRows();
    });
  }

  void _addRow(int max) {
    if (_options.length >= max) return;
    setState(() {
      _options.add(TextEditingController());
      if (_type == QuestionType.matching) _rights.add(TextEditingController());
    });
  }

  void _removeRow(int index) {
    setState(() {
      _retired.add(_options.removeAt(index));
      if (_type == QuestionType.matching && index < _rights.length) {
        _retired.add(_rights.removeAt(index));
      }
      if (_type == QuestionType.multipleChoice) {
        if (_answerIndex == index) {
          _answerIndex = 0;
        } else if (_answerIndex > index) {
          _answerIndex--;
        }
      }
    });
  }

  List<String> _texts(List<TextEditingController> list) =>
      [for (final c in list) c.text.trim()];

  /// Հավաքում է հարցը ձևից։ Սխալի դեպքում վերադարձնում է հաղորդագրություն։
  ({Question? question, String? error}) _build() {
    final json = <String, dynamic>{
      'type': _type.name,
      'difficulty': _difficulty,
      'prompt': _prompt.text.trim(),
      'explanation': _explanation.text.trim(),
    };
    if (_prompt.text.trim().isEmpty) {
      return (question: null, error: 'Գրեք հարցի տեքստը։');
    }

    switch (_type) {
      case QuestionType.multipleChoice:
        final options = _texts(_options);
        if (options.any((o) => o.isEmpty)) {
          return (question: null, error: 'Լրացրեք բոլոր տարբերակները կամ ջնջեք ավելորդները։');
        }
        if (options.toSet().length != options.length) {
          return (question: null, error: 'Տարբերակները չպետք է կրկնվեն։');
        }
        json['options'] = options;
        json['answerIndex'] = _answerIndex;
      case QuestionType.trueFalse:
        json['answerIndex'] = _answerIndex.clamp(0, 1);
      case QuestionType.fillBlank:
      case QuestionType.code:
        final accepted = [
          for (final line in _accepted.text.split('\n'))
            if (line.trim().isNotEmpty) line.trim(),
        ];
        if (accepted.isEmpty) {
          return (question: null, error: 'Գրեք առնվազն մեկ ընդունելի պատասխան։');
        }
        json['accepted'] = accepted;
      case QuestionType.numeric:
        final value = double.tryParse(_numeric.text.trim().replaceAll(',', '.'));
        if (value == null) {
          return (question: null, error: 'Ճիշտ պատասխանը պետք է լինի թիվ։');
        }
        json['numericAnswer'] = value;
      case QuestionType.ordering:
        final items = _texts(_options);
        if (items.length < 2 || items.any((o) => o.isEmpty)) {
          return (question: null, error: 'Լրացրեք առնվազն երկու տարր՝ առանց դատարկ դաշտերի։');
        }
        json['options'] = items;
      case QuestionType.matching:
        final lefts = _texts(_options);
        final rights = _texts(_rights);
        if (lefts.length < 2 ||
            lefts.any((o) => o.isEmpty) ||
            rights.any((o) => o.isEmpty)) {
          return (question: null, error: 'Լրացրեք առնվազն երկու զույգ՝ առանց դատարկ դաշտերի։');
        }
        json['options'] = lefts;
        json['rights'] = rights;
      case QuestionType.open:
        json['keywords'] = [
          for (final word in _keywords.text.split(','))
            if (word.trim().isNotEmpty) word.trim(),
        ];
    }

    try {
      final question = Question.fromJson(
        json,
        id: widget.existing?.id ?? ContentStore.instance.newId('q'),
        subjectId: widget.topic.subjectId,
        topicId: widget.topic.id,
        generated: false,
      );
      return (question: question, error: null);
    } on FormatException {
      return (question: null, error: 'Հարցը լրիվ չէ՝ ստուգեք բոլոր դաշտերը։');
    }
  }

  Future<void> _save() async {
    final learn = LearnScope.of(context);
    final built = _build();
    if (built.error != null) {
      setState(() => _error = built.error);
      return;
    }
    setState(() {
      _busy = true;
      _error = null;
    });
    final error = await learn.saveQuestion(built.question!);
    if (!mounted) return;
    if (error != null) {
      setState(() {
        _busy = false;
        _error = error;
      });
      return;
    }
    Navigator.of(context).pop();
  }

  @override
  Widget build(BuildContext context) {
    final learn = LearnScope.of(context);
    if (!learn.isAdmin) return const _NoAccess();
    final scheme = Theme.of(context).colorScheme;
    return Scaffold(
      appBar: AppBar(
        title: Text(widget.existing == null ? 'Նոր հարց' : 'Խմբագրել հարցը'),
        actions: [
          TextButton(
            onPressed: _busy ? null : _save,
            child: const Text('Պահել'),
          ),
        ],
      ),
      body: Center(
        child: ConstrainedBox(
          constraints: const BoxConstraints(maxWidth: 720),
          child: ListView(
            padding: const EdgeInsets.fromLTRB(16, 8, 16, 32),
            children: [
              Text(
                widget.topic.title,
                style: TextStyle(color: scheme.onSurfaceVariant),
              ),
              const SizedBox(height: 12),
              DropdownButtonFormField<QuestionType>(
                initialValue: _type,
                decoration: const InputDecoration(labelText: 'Հարցի տեսակ'),
                items: [
                  for (final type in QuestionType.values)
                    DropdownMenuItem(value: type, child: Text(type.label)),
                ],
                onChanged: (type) {
                  if (type != null) _changeType(type);
                },
              ),
              const SizedBox(height: 16),
              const Text('Բարդություն (1՝ հեշտ, 5՝ դժվար)'),
              const SizedBox(height: 6),
              SegmentedButton<int>(
                showSelectedIcon: false,
                segments: [
                  for (var d = 1; d <= 5; d++)
                    ButtonSegment<int>(value: d, label: Text('$d')),
                ],
                selected: {_difficulty},
                onSelectionChanged: (selection) =>
                    setState(() => _difficulty = selection.first),
              ),
              const SizedBox(height: 16),
              TextField(
                controller: _prompt,
                minLines: 2,
                maxLines: 6,
                decoration: const InputDecoration(
                  labelText: 'Հարցի տեքստ',
                  alignLabelWithHint: true,
                ),
              ),
              const SizedBox(height: 16),
              ..._answerFields(scheme),
              const SizedBox(height: 16),
              TextField(
                controller: _explanation,
                minLines: 2,
                maxLines: 6,
                decoration: const InputDecoration(
                  labelText: 'Բացատրություն (ցուցադրվում է պատասխանից հետո)',
                  alignLabelWithHint: true,
                ),
              ),
              if (_error != null) ...[
                const SizedBox(height: 12),
                Text(_error!, style: TextStyle(color: scheme.error)),
              ],
              const SizedBox(height: 20),
              FilledButton.icon(
                onPressed: _busy ? null : _save,
                icon: const Icon(Icons.save_outlined),
                label: const Text('Պահել հարցը'),
              ),
            ],
          ),
        ),
      ),
    );
  }

  List<Widget> _answerFields(ColorScheme scheme) {
    switch (_type) {
      case QuestionType.multipleChoice:
        return [
          const Text('Տարբերակներ (նշեք ճիշտը)'),
          const SizedBox(height: 4),
          for (var i = 0; i < _options.length; i++)
            Row(
              children: [
                IconButton(
                  tooltip: 'Ճիշտ պատասխան',
                  icon: Icon(
                    _answerIndex == i ? Icons.check_circle : Icons.radio_button_unchecked,
                    color: _answerIndex == i ? scheme.primary : null,
                  ),
                  onPressed: () => setState(() => _answerIndex = i),
                ),
                Expanded(
                  child: Padding(
                    padding: const EdgeInsets.symmetric(vertical: 4),
                    child: TextField(
                      controller: _options[i],
                      decoration: InputDecoration(labelText: 'Տարբերակ ${i + 1}'),
                    ),
                  ),
                ),
                IconButton(
                  tooltip: 'Հեռացնել',
                  icon: const Icon(Icons.close),
                  onPressed: _options.length > 2 ? () => _removeRow(i) : null,
                ),
              ],
            ),
          if (_options.length < _maxChoices)
            Align(
              alignment: Alignment.centerLeft,
              child: TextButton.icon(
                onPressed: () => _addRow(_maxChoices),
                icon: const Icon(Icons.add),
                label: const Text('Ավելացնել տարբերակ'),
              ),
            ),
        ];
      case QuestionType.trueFalse:
        return [
          const Text('Ճիշտ պատասխանը'),
          const SizedBox(height: 6),
          SegmentedButton<int>(
            segments: const [
              ButtonSegment<int>(value: 0, label: Text('Ճիշտ')),
              ButtonSegment<int>(value: 1, label: Text('Սխալ')),
            ],
            selected: {_answerIndex.clamp(0, 1)},
            onSelectionChanged: (selection) =>
                setState(() => _answerIndex = selection.first),
          ),
        ];
      case QuestionType.fillBlank:
      case QuestionType.code:
        return [
          TextField(
            controller: _accepted,
            minLines: 2,
            maxLines: 6,
            decoration: InputDecoration(
              labelText: 'Ընդունելի պատասխաններ՝ յուրաքանչյուրը նոր տողում',
              helperText: _type == QuestionType.fillBlank
                  ? 'Մեծատառ/փոքրատառը և ավելորդ բացատները նշանակություն չունեն։'
                  : 'Գրեք ճիշտ կոդը կամ արտահայտությունը (կարող եք մի քանի տարբերակ տալ)։',
              alignLabelWithHint: true,
            ),
          ),
        ];
      case QuestionType.numeric:
        return [
          TextField(
            controller: _numeric,
            keyboardType: const TextInputType.numberWithOptions(decimal: true, signed: true),
            decoration: const InputDecoration(
              labelText: 'Ճիշտ պատասխան (թիվ)',
              helperText: 'Տասնորդականի համար կարելի է օգտագործել և՛ կետ, և՛ ստորակետ։',
            ),
          ),
        ];
      case QuestionType.ordering:
        return [
          const Text('Տարրերը ճիշտ հերթականությամբ'),
          const Text(
            'Դասի ժամանակ դրանք խառնվում են, իսկ սովորողը պետք է դասավորի։',
            style: TextStyle(fontSize: 12),
          ),
          const SizedBox(height: 4),
          for (var i = 0; i < _options.length; i++)
            Row(
              children: [
                SizedBox(width: 28, child: Text('${i + 1}.')),
                Expanded(
                  child: Padding(
                    padding: const EdgeInsets.symmetric(vertical: 4),
                    child: TextField(
                      controller: _options[i],
                      decoration: InputDecoration(labelText: 'Տարր ${i + 1}'),
                    ),
                  ),
                ),
                IconButton(
                  tooltip: 'Հեռացնել',
                  icon: const Icon(Icons.close),
                  onPressed: _options.length > 2 ? () => _removeRow(i) : null,
                ),
              ],
            ),
          if (_options.length < _maxItems)
            Align(
              alignment: Alignment.centerLeft,
              child: TextButton.icon(
                onPressed: () => _addRow(_maxItems),
                icon: const Icon(Icons.add),
                label: const Text('Ավելացնել տարր'),
              ),
            ),
        ];
      case QuestionType.matching:
        return [
          const Text('Համապատասխան զույգեր'),
          const SizedBox(height: 4),
          for (var i = 0; i < _options.length; i++)
            Row(
              children: [
                Expanded(
                  child: Padding(
                    padding: const EdgeInsets.symmetric(vertical: 4),
                    child: TextField(
                      controller: _options[i],
                      decoration: InputDecoration(labelText: 'Ձախ ${i + 1}'),
                    ),
                  ),
                ),
                const Padding(
                  padding: EdgeInsets.symmetric(horizontal: 8),
                  child: Icon(Icons.swap_horiz),
                ),
                Expanded(
                  child: Padding(
                    padding: const EdgeInsets.symmetric(vertical: 4),
                    child: TextField(
                      controller: _rights[i],
                      decoration: InputDecoration(labelText: 'Աջ ${i + 1}'),
                    ),
                  ),
                ),
                IconButton(
                  tooltip: 'Հեռացնել',
                  icon: const Icon(Icons.close),
                  onPressed: _options.length > 2 ? () => _removeRow(i) : null,
                ),
              ],
            ),
          if (_options.length < _maxPairs)
            Align(
              alignment: Alignment.centerLeft,
              child: TextButton.icon(
                onPressed: () => _addRow(_maxPairs),
                icon: const Icon(Icons.add),
                label: const Text('Ավելացնել զույգ'),
              ),
            ),
        ];
      case QuestionType.open:
        return [
          TextField(
            controller: _keywords,
            decoration: const InputDecoration(
              labelText: 'Հիմնաբառեր՝ ստորակետով բաժանված',
              helperText:
                  'Պատասխանը ճիշտ է, եթե պարունակում է հիմնաբառերի առնվազն կեսը։ '
                  'Եթե դատարկ է՝ ընդունվում է ցանկացած բավարար երկար պատասխան։',
            ),
          ),
        ];
    }
  }
}

