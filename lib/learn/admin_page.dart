  final bool showLogout;

  Future<void> _reset(BuildContext context) async {
    final learn = LearnScope.of(context);
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (context) => AlertDialog(
        title: const Text('Վերականգնե՞լ ստանդարտ նյութերը'),
        content: const Text(
          'Ձեր բոլոր փոփոխությունները՝ նոր և խմբագրված առարկաները, թեմաները և '
          'հարցերը, կջնջվեն, և կվերադառնան հավելվածի սկզբնական նյութերը։',
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: const Text('Չեղարկել'),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(context, true),
            child: const Text('Վերականգնել'),
          ),
        ],
      ),
    );
    if (confirmed != true) return;
    final error = await learn.resetContent();
